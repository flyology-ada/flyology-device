/*  Emits Flyology_VFIO.Thin.Constants from the host's Linux headers.
 *
 *  Every number this crate sends to the kernel comes from here. None is
 *  transcribed from documentation or memory: a wrong ioctl number produces
 *  EINVAL a long way from the mistake, and a wrong struct offset produces a
 *  kernel reading one field where another was meant.
 *
 *  Struct sizes and field offsets are emitted alongside the request numbers
 *  so that the Ada representation clauses can be checked against C at
 *  compile time rather than trusted. GNAT's 'Size excludes trailing padding
 *  where C's sizeof includes it, so the Ada side compares 'Object_Size.
 */
#define _GNU_SOURCE
#include <stdio.h>
#include <stddef.h>
