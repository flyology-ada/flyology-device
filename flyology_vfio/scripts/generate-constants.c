/*  Wraps a note into Ada comment lines no wider than the file's margin,
 *  so the generated source reads like the hand-written source beside it.  */
static void note_lines (const char *note)
{
  const int margin = 75;              /*  3 spaces + "--  " + text <= 79  */
  const char *p = note;

  while (*p)
    {
      int room = margin - 7, taken = 0, last_space = -1, i;

      for (i = 0; i < room && p[i]; i++)
        if (p[i] == ' ')
          last_space = i;

      if (p[i] == '\0')
        taken = i;
      else if (last_space > 0)
        taken = last_space;
      else
        taken = room;

      printf ("   --  %.*s\n", taken, p);
      p += taken;
      while (*p == ' ')
        p++;
    }
}

static void num (const char *name, unsigned long value, const char *note)
{
  note_lines (note);
  printf ("   %-34s : constant := %lu;\n\n", name, value);
}

static void hex (const char *name, unsigned long value, const char *note)
{
  note_lines (note);
  printf ("   %-34s : constant := 16#%lX#;\n\n", name, value);
}

